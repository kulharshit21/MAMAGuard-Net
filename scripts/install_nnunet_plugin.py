#!/usr/bin/env python3
"""Install a tiny discovery shim into the active nnU-Net environment."""
from __future__ import annotations

import argparse
from pathlib import Path

SHIM = '''# Generated by MAMAGuard-Net; implementation remains in the editable project.\nfrom mamaguardnet.nnunet.trainers import (\n    nnUNetTrainerMAMAGuardNoDA,\n    nnUNetTrainerMAMAGuardStandard,\n    nnUNetTrainerMAMAGuardIndependent,\n    nnUNetTrainerMAMAGuardShared,\n    nnUNetTrainerMAMAGuardKinetics,\n    nnUNetTrainerMAMAGuardSmoke,\n)\n'''


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    import nnunetv2

    target = Path(nnunetv2.__file__).resolve().parent / "training" / "nnUNetTrainer" / "variants" / "mamaguard_trainers.py"
    print(target)
    if not args.dry_run:
        target.write_text(SHIM, encoding="utf-8")
        print("Installed MAMAGuard trainer discovery shim.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

